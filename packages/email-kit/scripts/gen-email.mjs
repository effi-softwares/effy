#!/usr/bin/env node
// The only writer of src/generated/ and dist/, in one pass:
//
//  packages/design-system/src/tokens.css
//  │
//  ├─→ src/generated/tokens.generated.ts the palette, as literal hex, for TS consumers
//  ├─→ src/generated/theme.mjml the head fragment every template includes
//  │
//  src/templates/<id>.mjml ──MJML──→ dist/<id>.html review + lint artifact
//  src/text/<id>.txt.hbs ──copy──→ dist/<id>.txt review + lint artifact
//  dist/templates.generated.ts ← what the bundler sees
//  dist/manifest.json
//
// The.html is what makes a design change reviewable; the TS module is what esbuild bundles; the two
// are byte-compared by check-email.mjs. No minification (it breaks email clients). {{handlebars}} and
// Cognito's {####} pass through MJML for runtime substitution.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, resolve, basename } from "node:path";
import mjml2html from "mjml";

import { buildEmailTokens, validateEmailTokens, TYPE, LAYOUT } from "./lib/tokens.mjs";
import { buildThemeMjml } from "./lib/theme.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const PKG = resolve(here, "..");
const SRC = resolve(PKG, "src");
const GENERATED = resolve(SRC, "generated");
const TEMPLATES = resolve(SRC, "templates");
const TEXT = resolve(SRC, "text");
const DIST = resolve(PKG, "dist");

const BANNER = "// GENERATED by scripts/gen-email.mjs — DO NOT EDIT. Run `make email-gen`.\n";

function sha256(s) {
  return createHash("sha256").update(s, "utf8").digest("hex").slice(0, 16);
}

/** Emits the palette as literal hex for TypeScript consumers: no `var` may reach email output. */
function emitTokensTs(tokens) {
  const lines = [
    BANNER,
    "// Source of truth: packages/design-system/src/tokens.css.",
    "// ⚠ CSS custom properties are unsupported in Gmail (every platform), every Word-engine Outlook,",
    "// Outlook.com, Outlook mobile, Yahoo and AOL — essentially the whole audience. So the variables",
    "// live in the generator and only literal values reach a message.",
    "",
    "export const EMAIL_TOKENS = {",
    `  light: ${JSON.stringify(tokens.light, null, 4).replace(/\n/g, "\n  ")},`,
    `  dark: ${JSON.stringify(tokens.dark, null, 4).replace(/\n/g, "\n  ")},`,
    `  radiusSm: ${JSON.stringify(tokens.radiusSm)},`,
    "} as const;",
    "",
    `export const EMAIL_TYPE = ${JSON.stringify(TYPE, null, 2)} as const;`,
    "",
    `export const EMAIL_LAYOUT = ${JSON.stringify(LAYOUT, null, 2)} as const;`,
    "",
    "export type EmailTokenRole = keyof typeof EMAIL_TOKENS.light;",
    "",
  ];
  writeFileSync(resolve(GENERATED, "tokens.generated.ts"), lines.join("\n"));
}

/** Compiles one template, placeholders intact. */
function compile(filePath) {
  const src = readFileSync(filePath, "utf8");
  const { html, errors } = mjml2html(src, {
    filePath,
    validationLevel: "strict",
    // False: kept comments would ship the source's internal notes inside customer email. MSO
    // conditionals survive (MJML generates its ghost tables; ours is in mj-raw), and a check asserts it.
    keepComments: false,
    minify: false,
    // No automatic font imports: MJML would add a Google Fonts link and @import for Roboto in our
    // stack, a third-party request (and a tracking signal) on every message. No web font ships.
    fonts: {},
  });
  if (errors && errors.length) {
    const detail = errors.map((e) => `      ${e.formattedMessage ?? e.message}`).join("\n");
    throw new Error(`MJML refused ${basename(filePath)}:\n${detail}`);
  }
  return promoteHeading(html, basename(filePath));
}

/**
 * MJML renders every mj-text as a <div>, so a message has no semantic heading. The div carrying `e-h1`
 * becomes an <h1> with the same inline style plus `margin:0`: a heading for screen readers, the same
 * appearance, and no font size in a template.
 */
function promoteHeading(html, label) {
  // MJML puts css-class on the <td>; the styled element is the <div> inside it.
  const cell = /<td([^>]*\bclass="[^"]*\be-h1\b[^"]*"[^>]*)>([\s\S]*?)<\/td>/;
  const m = html.match(cell);
  if (!m) return html;

  // Exactly one heading per message, counted before promotion (the cell keeps its class).
  const headingCells = html.match(new RegExp(cell.source, "g")) ?? [];
  if (headingCells.length > 1) {
    throw new Error(
      `${label}: ${headingCells.length} e-h1 headings — a message has exactly one <h1>`,
    );
  }

  const inner = m[2];
  const divRe = /<div(\s[^>]*)?>([\s\S]*?)<\/div>/;
  const dm = inner.match(divRe);
  if (!dm) {
    throw new Error(`${label}: an e-h1 cell contains no styled element to promote`);
  }
  const attrs = dm[1] ?? "";
  const promotedAttrs = /style="/.test(attrs)
    ? attrs.replace(/style="/, 'style="margin:0;')
    : `${attrs} style="margin:0;"`;
  const promotedInner = inner.replace(divRe, `<h1${promotedAttrs}>${dm[2]}</h1>`);
  const out = html.replace(cell, `<td${m[1]}>${promotedInner}</td>`);

  return out;
}

function main() {
  // 1. Tokens, derived and validated before anything is written.
  const tokens = buildEmailTokens();
  const tokenErrors = validateEmailTokens(tokens);
  if (tokenErrors.length) {
    console.error("✗ email tokens are invalid:\n  - " + tokenErrors.join("\n  - "));
    process.exit(1);
  }

  mkdirSync(GENERATED, { recursive: true });
  emitTokensTs(tokens);
  writeFileSync(resolve(GENERATED, "theme.mjml"), buildThemeMjml(tokens));

  // 2. Every template.
  if (!existsSync(TEMPLATES)) {
    console.error(`✗ no templates directory at ${TEMPLATES}`);
    process.exit(1);
  }
  const ids = readdirSync(TEMPLATES)
    .filter((f) => f.endsWith(".mjml"))
    .map((f) => f.replace(/\.mjml$/, ""))
    .sort();

  if (!ids.length) {
    console.error("✗ no templates found — nothing to generate");
    process.exit(1);
  }

  // Only the artifacts we own; dist/preview/ is left alone.
  for (const f of existsSync(DIST) ? readdirSync(DIST) : []) {
    if (f.endsWith(".html") || f.endsWith(".txt") || f === "manifest.json" || f === "templates.generated.ts") {
      rmSync(resolve(DIST, f));
    }
  }
  mkdirSync(DIST, { recursive: true });

  const manifest = {};
  const bundle = {};

  for (const id of ids) {
    const html = compile(resolve(TEMPLATES, `${id}.mjml`));

    const textPath = resolve(TEXT, `${id}.txt.hbs`);
    if (!existsSync(textPath)) {
      // Required: HTML-only mail trips SpamAssassin's MIME_HTML_ONLY, and some clients preview from the text part.
      console.error(`✗ ${id}: no plain-text part at src/text/${id}.txt.hbs`);
      process.exit(1);
    }
    const text = readFileSync(textPath, "utf8");

    writeFileSync(resolve(DIST, `${id}.html`), html);
    writeFileSync(resolve(DIST, `${id}.txt`), text);

    bundle[id] = { html, text };
    manifest[id] = {
      htmlBytes: Buffer.byteLength(html, "utf8"),
      htmlChars: [...html].length,
      textBytes: Buffer.byteLength(text, "utf8"),
      htmlSha: sha256(html),
      textSha: sha256(text),
    };
  }

  // 3. The runtime artifact.
  const bundleLines = [
    BANNER,
    "// ⚠ This is what the LAMBDA BUNDLER sees. The matching dist/<id>.html files are the review and",
    "// lint artifacts; check-email.mjs asserts the two carry byte-identical content.",
    "",
    "export interface CompiledTemplate {",
    "  readonly html: string;",
    "  readonly text: string;",
    "}",
    "",
    "export const COMPILED_TEMPLATES: Readonly<Record<string, CompiledTemplate>> = {",
    ...ids.map((id) => `  ${JSON.stringify(id)}: {\n    html: ${JSON.stringify(bundle[id].html)},\n    text: ${JSON.stringify(bundle[id].text)},\n  },`),
    "};",
    "",
  ];
  writeFileSync(resolve(DIST, "templates.generated.ts"), bundleLines.join("\n"));
  writeFileSync(resolve(DIST, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

  console.log(`✓ email-gen — ${ids.length} template(s)`);
  for (const id of ids) {
    const m = manifest[id];
    console.log(`    ${id.padEnd(32)} ${String(m.htmlBytes).padStart(6)} B html · ${String(m.textBytes).padStart(5)} B text`);
  }
}

main();
