export function categoryIconComponent(key: CategoryIcon | null | undefined): LucideIcon {
  return CATEGORY_ICON_COMPONENTS[key ?? CATEGORY_ICON_FALLBACK] ?? CATEGORY_ICON_COMPONENTS[CATEGORY_ICON_FALLBACK]
}

/** The glyph, decorative (the category's name is always written beside it). */
export function CategoryGlyph({ icon, ...props }: { icon: CategoryIcon | null | undefined } & LucideProps) {
  const Icon = categoryIconComponent(icon)
  return <Icon aria-hidden {...props} />
}
